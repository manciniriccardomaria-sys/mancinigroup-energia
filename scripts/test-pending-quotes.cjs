const assert = require("node:assert/strict");
const fs = require("node:fs");
const ts = require("typescript");
require.extensions[".ts"] = (module, filename) => {
  module._compile(ts.transpileModule(fs.readFileSync(filename, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }
  }).outputText, filename);
};
const { normalizeStore, cloneStore, addEnergyQuoteToStore, importLoadingRecordsToStore } = require("../src/lib/client-store.ts");
const { savePendingQuote, visiblePendingQuotes, completePendingQuote, pendingQuoteStatus, setPendingQuoteStatus, convertPendingQuote } = require("../src/lib/pending-quotes.ts");
const { normalizePodPdr } = require("../src/lib/normalize.ts");
const admin = { id: "admin", role: "admin" };
const agent = { id: "agent", role: "agent", sourceId: "source-agent" };
const other = { id: "other", role: "frontline", sourceId: "source-other" };
const store = normalizeStore({});
store.sources.push({ id: agent.sourceId, name: "Fonte agente", kind: "collaboratore", active: true });
store.sources.push({ id: other.sourceId, name: "Altra fonte", kind: "frontline", active: true });
assert.deepEqual(store.pendingEnergyQuotes, []);
assert.equal(pendingQuoteStatus({}), "da_preventivare");
assert.equal(pendingQuoteStatus({ completedQuoteId: "old" }), "preventivato");
assert.throws(() => savePendingQuote(store, agent, { firstName: "", lastName: "Rossi", commodity: "luce", customerType: "RES" }));
const bill = { id: "bill-test", originalName: "bolletta.pdf", mimeType: "application/pdf", size: 20, chunkCount: 1, uploadedBy: agent.id, uploadedAt: "2026-10-12" };
savePendingQuote(store, agent, { firstName: " Mario ", lastName: " Rossi ", phone: " 123 ", commodity: "gas", customerType: "BUS", sourceId: "forbidden", notes: " Recuperare bolletta ", dueDate: "2026-10-20", attachments: [bill] });
const request = store.pendingEnergyQuotes[0];
assert.equal(request.sourceId, agent.sourceId);
assert.equal(request.firstName, "Mario");
assert.equal(request.notes, "Recuperare bolletta");
assert.equal(pendingQuoteStatus(request), "da_preventivare");
assert.equal(visiblePendingQuotes(store, other).length, 0);
assert.equal(visiblePendingQuotes(store, admin).length, 1);
assert.throws(() => savePendingQuote(store, other, request, request.id));
assert.throws(() => completePendingQuote(store, other, request.id, "unknown"));
assert.throws(() => setPendingQuoteStatus(store, other, request.id, "preventivato"));
savePendingQuote(store, admin, { ...request, phone: "456" }, request.id);
assert.equal(store.pendingEnergyQuotes.length, 1);
assert.equal(request.phone, "456");
assert.equal(request.createdBy, agent.id);
savePendingQuote(store, agent, { ...request, createdBy: other.id, completedQuoteId: "forbidden", status: "convertito" }, request.id);
assert.equal(request.createdBy, agent.id);
assert.equal(request.completedQuoteId, undefined);
assert.equal(request.status, "da_preventivare");
const roundTrip = normalizeStore(JSON.parse(JSON.stringify(cloneStore(store))));
assert.deepEqual(roundTrip.pendingEnergyQuotes[0], request);
assert.deepEqual(roundTrip.pendingEnergyQuotes[0].attachments, [bill]);
addEnergyQuoteToStore(store, { commodity: request.commodity, customerFirstName: request.firstName, customerLastName: request.lastName, createdBy: agent.id, inputSnapshot: {} });
completePendingQuote(store, agent, request.id, store.energyQuotes[0].id);
assert.equal(request.completedQuoteId, store.energyQuotes[0].id);
assert.equal(pendingQuoteStatus(request), "preventivato");
assert.equal(visiblePendingQuotes(store, admin).length, 1, "Prepared requests must remain in the workflow");
setPendingQuoteStatus(store, agent, request.id, "inviato_alla_fonte");
assert.equal(pendingQuoteStatus(request), "inviato_alla_fonte");
completePendingQuote(store, agent, request.id, store.energyQuotes[0].id);
assert.equal(pendingQuoteStatus(request), "inviato_alla_fonte", "Recalculation must not regress workflow");
savePendingQuote(store, agent, { ...request, notes: "Preventivo inviato" }, request.id);
assert.equal(request.attachments.length, 1);
assert.throws(() => setPendingQuoteStatus(store, admin, request.id, "convertito"));
assert.throws(() => convertPendingQuote(store, agent, request.id, "00123456789012"));
assert.throws(() => convertPendingQuote(store, admin, request.id, "IT001E12345678"));
assert.throws(() => convertPendingQuote(store, admin, request.id, "123"));
const pdr = "00123456789012";
const normalized = normalizePodPdr(pdr);
store.loadingRecords.push({ id: "existing-loading", podPdr: pdr, podPdrNorm: normalized });
convertPendingQuote(store, admin, request.id, pdr);
const customer = store.customers.find((item) => item.podPdrNorm === normalized);
assert.ok(customer);
assert.equal(customer.sourceId, agent.sourceId);
assert.equal(customer.name, "Mario Rossi");
assert.equal(customer.status, "in_lavorazione");
assert.equal(request.status, "convertito");
assert.equal(request.podPdr, pdr, "Preserve original PDR leading zeros");
assert.equal(request.convertedCustomerId, customer.id);
assert.equal(store.loadingRecords[0].matchedSourceId, agent.sourceId, "Match already imported contracts");
assert.throws(() => convertPendingQuote(store, admin, request.id, pdr));
assert.throws(() => setPendingQuoteStatus(store, admin, request.id, "da_preventivare"));
assert.throws(() => savePendingQuote(store, admin, { ...request, sourceId: other.sourceId }, request.id));
const row = { podPdr: pdr, podPdrNorm: normalized, monthKey: "2026-11", rowNumber: 1, customerName: "Mario Rossi", commodity: "gas" };
importLoadingRecordsToStore(store, { uploadedFileId: "future-upload", rows: [row], totalRows: 1, skippedRows: 0 });
assert.equal(store.loadingRecords.find((record) => record.uploadedFileId === "future-upload").matchedSourceId, agent.sourceId, "Automatically match future imports");
const duplicate = savePendingQuote(store, admin, { firstName: "Mario", lastName: "Rossi", commodity: "gas", customerType: "RES", sourceId: agent.sourceId });
const countBefore = store.customers.length;
convertPendingQuote(store, admin, duplicate.id, pdr);
assert.equal(store.customers.length, countBefore);
assert.equal(duplicate.convertedCustomerId, customer.id);
const conflict = savePendingQuote(store, admin, { firstName: "Altro", lastName: "Cliente", commodity: "gas", customerType: "RES", sourceId: other.sourceId });
assert.throws(() => convertPendingQuote(store, admin, conflict.id, pdr), /altra fonte/);
assert.equal(customer.sourceId, agent.sourceId);
assert.equal(conflict.status, "da_preventivare");
const light = savePendingQuote(store, admin, { firstName: "Anna", lastName: "Verdi", commodity: "luce", customerType: "RES", sourceId: agent.sourceId });
convertPendingQuote(store, admin, light.id, "it001e12345678");
assert.equal(light.podPdr, "IT001E12345678");
assert.equal(store.customers.find((item) => item.id === light.convertedCustomerId).commodity, "luce");
const noSource = savePendingQuote(store, admin, { firstName: "Senza", lastName: "Fonte", commodity: "luce", customerType: "RES" });
assert.throws(() => setPendingQuoteStatus(store, admin, noSource.id, "inviato_alla_fonte"));
assert.throws(() => convertPendingQuote(store, admin, noSource.id, "IT001E12345679"));
console.log("Pending quote checks passed: attachments, legacy statuses, ownership, workflow, POD/PDR validation, conversion, duplicate protection and future loading matches.");
